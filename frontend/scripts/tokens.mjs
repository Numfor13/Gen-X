// Generates app/tokens.css: Material 3 colour roles (2025 spec) and Expressive spring easings.
// Run with `npm run tokens` after changing a seed. The output is committed; nothing here ships to the browser.
import { writeFileSync } from "node:fs";
import { register } from "node:module";

// The library's ESM files import each other without ".js", which Node rejects: retry with the extension.
register("data:text/javascript," + encodeURIComponent(
  `export async function resolve(s, c, next) {
     try { return await next(s, c); }
     catch (e) { if (e.code === "ERR_MODULE_NOT_FOUND") return next(s + ".js", c); throw e; }
   }`));
const { argbFromHex, hexFromArgb, Hct, SchemeFidelity, MaterialDynamicColors } =
  await import("@material/material-color-utilities");

const SEEDS = { primary: "#B5562B", secondary: "#1F6B4A", tertiary: "#2E4A9E" }; // ochre, forest, indigo

const scheme = (hex) => new SchemeFidelity(Hct.fromInt(argbFromHex(hex)), false, 0, "2025");
const kebab = (s) => s.replace(/_/g, "-").replace(/([A-Z])/g, "-$1").toLowerCase();
const roles = (s) =>
  Object.fromEntries(new MaterialDynamicColors().allColors.map((c) => [kebab(c.name), hexFromArgb(c.getArgb(s))]));

const colors = roles(scheme(SEEDS.primary));
// Secondary and tertiary are brand colours of their own, not tints of the primary:
// take the primary family of a scheme seeded with each.
for (const family of ["secondary", "tertiary"]) {
  const r = roles(scheme(SEEDS[family]));
  for (const [from, to] of [["primary", family], ["on-primary", `on-${family}`],
    ["primary-container", `${family}-container`], ["on-primary-container", `on-${family}-container`],
    ["primary-fixed", `${family}-fixed`], ["on-primary-fixed", `on-${family}-fixed`]]) {
    colors[to] = r[from];
  }
}

// Damped spring sampled into a CSS linear() easing (mass 1).
function spring(stiffness, ratio, points = 32) {
  const w = Math.sqrt(stiffness), T = Math.log(1000) / (ratio * w);
  const wd = w * Math.sqrt(Math.max(1e-6, 1 - ratio * ratio));
  const xs = Array.from({ length: points + 1 }, (_, i) => {
    const t = (i / points) * T;
    const x = ratio < 1
      ? 1 - Math.exp(-ratio * w * t) * (Math.cos(wd * t) + ((ratio * w) / wd) * Math.sin(wd * t))
      : 1 - Math.exp(-w * t) * (1 + w * t);
    return +x.toFixed(3);
  });
  return [`linear(${xs.join(", ")})`, `${Math.round(T * 1000)}ms`];
}
const springs = { "fast-spatial": spring(800, 0.6), "default-spatial": spring(380, 0.8), "default-effects": spring(1600, 1) };

const lines = [
  ...Object.entries(colors).map(([k, v]) => `  --md-sys-color-${k}: ${v};`),
  "  --md-sys-color-gold: #f2b705;",
  ...Object.entries(springs).flatMap(([k, [easing, ms]]) => [`  --spring-${k}: ${easing};`, `  --spring-${k}-ms: ${ms};`]),
];
writeFileSync(new URL("../app/tokens.css", import.meta.url), `/* Generated by scripts/tokens.mjs. Do not edit. */\n:root {\n${lines.join("\n")}\n}\n`);
